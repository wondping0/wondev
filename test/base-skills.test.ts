import { afterEach, beforeEach, expect, it } from 'vitest';
import { runInit } from '../src/commands/init.js';
import { loadContext } from '../src/commands/context.js';
import { BASE_SKILLS } from '../src/core/base-skills.js';
import { evaluateTriggers, validateSkill } from '../src/core/skill-quality.js';
import { cleanup, silence, tmpRoot, write } from './helpers.js';

let root: string;
beforeEach(async () => { root = await tmpRoot(); });
afterEach(async () => { await cleanup(root); });

it('ships valid on-demand skills with actual resources and distinct task triggers', async () => {
  await silence(() => runInit(root, { targets: ['agents'], skipBuild: true }));
  const { project } = await loadContext(root);
  expect(project.skills.map((s) => s.name)).toEqual(BASE_SKILLS.map((s) => s.name).sort());
  for (const skill of project.skills) {
    expect(validateSkill(skill), skill.name).toEqual([]);
    if (['ui-ux-pro-max', 'understand-anything', 'webapp-testing', 'skill-discovery', 'context-maintenance'].includes(skill.name)) expect(skill.inline).toBe(false);
  }
  expect(project.skills.find((s) => s.name === 'ui-ux-pro-max')?.attachments.map((a) => a.relPath)).toContain('scripts/design_system.py');
  expect(project.skills.find((s) => s.name === 'understand-anything')?.attachments.map((a) => a.relPath)).toContain('references/upstream-understand.md');
  const results = evaluateTriggers(project, [
    { task: 'Design responsive typography and palettes', expected: ['ui-ux-pro-max'] },
    { task: 'Map application architecture and component relationships', expected: ['understand-anything'] },
    { task: 'Test browser rendering with Playwright screenshots', expected: ['webapp-testing'] },
    { task: 'Find and disable agent skills and plugins', expected: ['skill-discovery'] },
    { task: 'Review stale memory and record development lessons', expected: ['context-maintenance'] },
    { task: 'Rotate PostgreSQL credentials', expected: [], forbidden: ['ui-ux-pro-max', 'webapp-testing'] },
  ]);
  expect(results.filter((r) => !r.passed)).toEqual([]);
});

it('does not compile Python runtime caches generated by using a bundled script', async () => {
  await silence(() => runInit(root, { targets: ['agents'], skipBuild: true }));
  await write(root, '.wondev/skills/ui-ux-pro-max/scripts/__pycache__/core.cpython-313.pyc', 'cache');
  await write(root, '.wondev/skills/ui-ux-pro-max/scripts/legacy.pyc', 'cache');
  const { project } = await loadContext(root);
  expect(project.skills.find((s) => s.name === 'ui-ux-pro-max')?.attachments.some((a) => a.relPath.endsWith('.pyc'))).toBe(false);
});

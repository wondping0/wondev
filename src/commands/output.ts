import type { NamedTarget } from '../core/model.js';
import { renderAll, type RenderResult } from '../core/render/index.js';
import { inspectFreshness } from '../core/freshness.js';
import { assertOutputPaths, type ProjectContext } from './context.js';
import { WondevError } from '../util/errors.js';

export const REVIEW_OWNER = 'memory-review';

export async function projectOutput(ctx: ProjectContext, targets: NamedTarget[]): Promise<RenderResult> {
  const result = renderAll(ctx.project, targets, ctx.config.index);
  if (ctx.config.vault) {
    const file = `${ctx.config.vault}/review.md`;
    if (result.files.some((f) => f.path === file)) throw new WondevError(`Vault review path is already an output: ${file}`);
    const report = await inspectFreshness(ctx.root, ctx.project.memory);
    const cell = (value: string): string => value.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
    const rows = report.map((item) => {
      const doc = ctx.project.memory.find((m) => m.sourcePath === item.path)!;
      return `| [[${doc.vaultPath ?? doc.slug}]] | ${item.status} | ${cell(item.reasons.join('; '))} |`;
    });
    result.files.push({ path: file, mode: 'region', content: [
      '# Memory review',
      'Regenerated by `wondev build`. A changed fingerprint means review is needed, not that a claim is false. After checking the code, run `wondev memory verify <id> --against "what you checked"`, then rebuild.',
      '| Note | Evidence | Reason |\n| --- | --- | --- |',
      rows.join('\n'),
    ].join('\n\n') + '\n' });
    result.owners.set(file, REVIEW_OWNER);
  }
  assertOutputPaths(ctx, result.files);
  return result;
}

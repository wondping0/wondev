import type { RenderedFile, WriteMode } from './model.js';
import { WONDEV_DIR } from './config.js';
import { WondevError } from '../util/errors.js';
import {
  normalizeEol,
  pruneEmptyDirs,
  readFileIfExists,
  removeFile,
  sha256,
  writeFileAtomic,
} from '../util/fs.js';
import { absFrom, createRootGuard, isInsideRoot } from '../util/paths.js';
import { IO_CONCURRENCY, mapLimit } from '../util/async.js';
import { wondevVersion } from '../util/version.js';
import { MANIFEST_SCHEMA_VERSION } from './schema.js';

export const MANIFEST_REL = `${WONDEV_DIR}/.manifest.json`;
export const REGION_START = '<!-- wondev:start -->';
export const REGION_END = '<!-- wondev:end -->';
export const GENERATED_HEADER =
  '<!-- Generated by wondev. Edit .wondev/ and run `wondev build`. -->';

export interface ManifestEntry {
  /** sha256 of the span wondev owns: the whole file, or the text between the markers. */
  hash: string;
  target: string;
  mode: WriteMode;
}

export interface Manifest {
  version: number;
  /** The wondev release that produced these files. Absent in manifests written before 0.2. */
  wondevVersion?: string;
  files: Record<string, ManifestEntry>;
}

export function emptyManifest(): Manifest {
  return { version: MANIFEST_SCHEMA_VERSION, files: {} };
}

export async function loadManifest(root: string): Promise<Manifest> {
  const raw = await readFileIfExists(absFrom(root, MANIFEST_REL));
  if (raw === null) return emptyManifest();

  let parsed: Manifest;
  try {
    parsed = JSON.parse(raw) as Manifest;
  } catch {
    // A corrupt manifest must not brick the project; treating it as empty makes every
    // existing output look untracked, which surfaces as a refuse-to-clobber message.
    return emptyManifest();
  }

  if (typeof parsed !== 'object' || parsed === null || typeof parsed.files !== 'object') {
    return emptyManifest();
  }

  // A manifest from the future is refused rather than reinterpreted: guessing at an unknown
  // format risks deleting files this build cannot correctly account for.
  if (typeof parsed.version === 'number' && parsed.version > MANIFEST_SCHEMA_VERSION) {
    throw new WondevError(
      `${MANIFEST_REL} uses format version ${parsed.version}, but this wondev supports up to ${MANIFEST_SCHEMA_VERSION}.`,
      'Upgrade wondev: npm install -g wondev@latest',
    );
  }

  // The manifest drives deletion, and it lives in the repository, so it is untrusted input.
  // A crafted entry such as "../../.ssh/authorized_keys" would otherwise make `clean` or a
  // stale-file sweep delete files outside the project. wondev never writes such a path, so
  // finding one means the file was tampered with: fail loudly rather than sanitise quietly.
  const unsafe = Object.keys(parsed.files ?? {}).filter((p) => !isInsideRoot(p));
  if (unsafe.length > 0) {
    throw new WondevError(
      `${MANIFEST_REL} contains ${unsafe.length} path(s) outside the project: ${unsafe.slice(0, 3).join(', ')}`,
      'wondev never writes such paths. Delete .wondev/.manifest.json and re-run `wondev build`.',
    );
  }

  const manifest: Manifest = {
    version: parsed.version ?? MANIFEST_SCHEMA_VERSION,
    files: parsed.files ?? {},
  };
  if (typeof parsed.wondevVersion === 'string') manifest.wondevVersion = parsed.wondevVersion;
  return manifest;
}

export async function saveManifest(root: string, manifest: Manifest): Promise<void> {
  const sorted: Manifest = {
    version: MANIFEST_SCHEMA_VERSION,
    wondevVersion: wondevVersion(),
    files: Object.fromEntries(
      Object.entries(manifest.files).sort(([a], [b]) => a.localeCompare(b)),
    ),
  };
  await writeFileAtomic(absFrom(root, MANIFEST_REL), `${JSON.stringify(sorted, null, 2)}\n`);
}

export type PlanAction = 'create' | 'update' | 'unchanged' | 'adopt';
export type ConflictReason = 'untracked' | 'modified';

export interface PlanItem {
  path: string;
  mode: WriteMode;
  target: string;
  action: PlanAction;
  /** Exact bytes to write. Already includes header and markers. */
  nextContent: string;
  /** Hash of the span wondev owns, stored in the manifest after a successful write. */
  ownedHash: string;
  conflict?: ConflictReason;
}

function regionInner(content: string): string {
  return `\n${GENERATED_HEADER}\n\n${content.trim()}\n`;
}

function buildRegionBlock(content: string): string {
  return `${REGION_START}${regionInner(content)}${REGION_END}`;
}

const REGION_RE = new RegExp(`${REGION_START}([\\s\\S]*?)${REGION_END}`);

/** The text wondev owns inside an existing file, or null when it owns nothing yet. */
export function extractRegion(fileContent: string): string | null {
  const m = REGION_RE.exec(fileContent);
  return m ? (m[1] ?? '') : null;
}

function replaceRegion(existing: string, content: string): string {
  const block = buildRegionBlock(content);
  if (REGION_RE.test(existing)) {
    return existing.replace(REGION_RE, () => block);
  }
  // Additive: the user's file is preserved and the managed block is appended. This is why
  // `region` is the default mode -- adopting an existing AGENTS.md never destroys anything.
  const base = existing.trimEnd();
  return base === '' ? `${block}\n` : `${base}\n\n${block}\n`;
}

const LEADING_FRONTMATTER = /^---[ \t]*\r?\n[\s\S]*?\r?\n---[ \t]*\r?\n/;

/**
 * Prepend the "generated" notice, but never above a frontmatter block.
 *
 * Cursor only recognises a `.mdc` rule when its YAML frontmatter starts at the first byte;
 * a comment above it makes the rule silently inert. The same is true of Claude Code skills.
 */
function wholeContent(content: string): string {
  const trimmed = content.trim();
  const fm = LEADING_FRONTMATTER.exec(trimmed);
  if (fm && fm[0]) {
    const body = trimmed.slice(fm[0].length).trim();
    return `${fm[0]}\n${GENERATED_HEADER}\n\n${body}\n`;
  }
  return `${GENERATED_HEADER}\n\n${trimmed}\n`;
}

/**
 * Decide what would happen to each rendered file without touching disk.
 *
 * The refusal rules live here so `build`, `--dry-run`, and `check` all agree on what counts
 * as a conflict.
 */
export async function planWrites(
  root: string,
  files: RenderedFile[],
  targetOf: Map<string, string>,
  manifest: Manifest,
): Promise<PlanItem[]> {
  // Every output path is resolved through symlinks before it is read or written. A cloned
  // repository can contain a directory symlink pointing outside itself, which the lexical
  // check alone would not catch.
  //
  // The lexical test is per file and free; the symlink resolution is per directory, so only
  // one representative path per directory needs to reach the filesystem.
  const ensureInside = createRootGuard(root);
  const representativeByDir = new Map<string, string>();
  for (const file of files) {
    if (!isInsideRoot(file.path)) {
      throw new WondevError(`Path escapes the project: ${file.path}`);
    }
    const dir = path.posix.dirname(file.path);
    if (!representativeByDir.has(dir)) representativeByDir.set(dir, file.path);
  }
  await mapLimit([...representativeByDir.values()], IO_CONCURRENCY, ensureInside);

  // Reading the existing output dominates this command's wall clock on any real project, so
  // it happens up front with bounded concurrency. The decision logic below stays sequential
  // and unchanged, which keeps the plan deterministic.
  const existingContents = await mapLimit(files, IO_CONCURRENCY, async (file) => {
    const raw = await readFileIfExists(absFrom(root, file.path));
    return raw === null ? null : normalizeEol(raw);
  });

  const plan: PlanItem[] = [];

  for (const [index, file] of files.entries()) {
    const existing = existingContents[index] ?? null;
    const entry = manifest.files[file.path];
    const target = targetOf.get(file.path) ?? 'unknown';

    if (file.mode === 'whole') {
      const next = wholeContent(file.content);
      const ownedHash = sha256(next);

      if (existing === null) {
        plan.push({ path: file.path, mode: 'whole', target, action: 'create', nextContent: next, ownedHash });
        continue;
      }
      if (!entry) {
        plan.push({
          path: file.path, mode: 'whole', target, action: 'update',
          nextContent: next, ownedHash, conflict: 'untracked',
        });
        continue;
      }
      if (sha256(existing) !== entry.hash) {
        plan.push({
          path: file.path, mode: 'whole', target, action: 'update',
          nextContent: next, ownedHash, conflict: 'modified',
        });
        continue;
      }
      plan.push({
        path: file.path, mode: 'whole', target,
        action: existing === next ? 'unchanged' : 'update',
        nextContent: next, ownedHash,
      });
      continue;
    }

    // region mode
    const inner = regionInner(file.content);
    const ownedHash = sha256(inner);

    if (existing === null) {
      plan.push({
        path: file.path, mode: 'region', target, action: 'create',
        nextContent: `${buildRegionBlock(file.content)}\n`, ownedHash,
      });
      continue;
    }

    const currentInner = extractRegion(existing);
    const next = replaceRegion(existing, file.content);

    if (currentInner === null) {
      // No markers yet. Appending is non-destructive, so this is allowed without --force.
      plan.push({ path: file.path, mode: 'region', target, action: 'adopt', nextContent: next, ownedHash });
      continue;
    }
    if (!entry) {
      plan.push({
        path: file.path, mode: 'region', target, action: 'update',
        nextContent: next, ownedHash, conflict: 'untracked',
      });
      continue;
    }
    if (sha256(currentInner) !== entry.hash) {
      plan.push({
        path: file.path, mode: 'region', target, action: 'update',
        nextContent: next, ownedHash, conflict: 'modified',
      });
      continue;
    }
    plan.push({
      path: file.path, mode: 'region', target,
      action: currentInner === inner ? 'unchanged' : 'update',
      nextContent: next, ownedHash,
    });
  }

  return plan;
}

export function conflictsIn(plan: PlanItem[]): PlanItem[] {
  return plan.filter((p) => p.conflict !== undefined);
}

export function describeConflicts(conflicts: PlanItem[]): WondevError {
  const lines = conflicts.map((c) =>
    c.conflict === 'untracked'
      ? `  ${c.path} — exists but was not written by wondev`
      : `  ${c.path} — has been edited since wondev wrote it`,
  );
  return new WondevError(
    `Refusing to overwrite ${conflicts.length} file(s):\n${lines.join('\n')}`,
    'Re-run with --force to overwrite, or move your edits into .wondev/ first.',
  );
}

export interface ApplyResult {
  written: PlanItem[];
  removed: RemovedFile[];
}

/**
 * Write the plan and reconcile the manifest.
 *
 * Files the manifest still lists but the current render no longer produces are removed, so
 * deleting a skill from `.wondev/` cleans up its generated output everywhere.
 */
export async function applyPlan(
  root: string,
  plan: PlanItem[],
  manifest: Manifest,
  builtTargets?: Set<string>,
): Promise<ApplyResult> {
  const written = plan.filter((item) => item.action !== 'unchanged');

  // Writes are independent: each goes to its own path via a uniquely named temp file, so
  // running them concurrently cannot interleave. Ordering only matters for the report,
  // which uses `written` rather than completion order.
  await mapLimit(written, IO_CONCURRENCY, async (item) => {
    await writeFileAtomic(absFrom(root, item.path), item.nextContent);
  });

  for (const item of plan) {
    manifest.files[item.path] = { hash: item.ownedHash, target: item.target, mode: item.mode };
  }

  // A build that rendered only some targets can only speak for those targets. Without this,
  // `build --target claude` sees every other target's output as unrendered, concludes it is
  // stale, and deletes it -- turning a narrowing flag into a destructive one.
  const rendered = new Set(plan.map((p) => p.path));
  const stale = Object.keys(manifest.files).filter((p) => {
    if (rendered.has(p)) return false;
    if (!builtTargets) return true;
    const entry = manifest.files[p];
    return entry !== undefined && builtTargets.has(entry.target);
  });
  const removed: RemovedFile[] = [];
  for (const p of stale) {
    const entry = manifest.files[p];
    if (!entry) continue;
    const outcome = await removeOwned(root, p, entry.mode);
    if (outcome !== 'missing') removed.push({ path: p, outcome });
    delete manifest.files[p];
  }

  await saveManifest(root, manifest);
  return { written, removed };
}

/** What happened to a file wondev stopped owning. */
export type RemoveOutcome = 'deleted' | 'stripped' | 'missing';

export interface RemovedFile {
  path: string;
  outcome: RemoveOutcome;
}

/**
 * Remove wondev's contribution to a file. A `whole` file is deleted outright; a `region`
 * file loses only its managed block and keeps whatever the user wrote around it, which is
 * why the two outcomes are reported separately rather than both as "removed".
 */
export async function removeOwned(
  root: string,
  rel: string,
  mode: WriteMode,
): Promise<RemoveOutcome> {
  // Defence in depth. `loadManifest` already rejects escaping paths, but this is the only
  // function in wondev that deletes, so it re-checks no matter who called it -- lexically,
  // and then through any symlink on the way.
  if (!isInsideRoot(rel)) {
    throw new WondevError(`Refusing to delete outside the project: ${rel}`);
  }
  await createRootGuard(root)(rel);

  const abs = absFrom(root, rel);
  const raw = await readFileIfExists(abs);
  if (raw === null) return 'missing';

  if (mode === 'whole') {
    await removeFile(abs);
    await pruneEmptyDirs(path.dirname(abs), root);
    return 'deleted';
  }

  const content = normalizeEol(raw);
  if (!REGION_RE.test(content)) return 'missing';
  const stripped = content.replace(REGION_RE, '').replace(/\n{3,}/g, '\n\n').trim();
  if (stripped === '') {
    await removeFile(abs);
    await pruneEmptyDirs(path.dirname(abs), root);
    return 'deleted';
  }
  await writeFileAtomic(abs, `${stripped}\n`);
  return 'stripped';
}

/** Remove everything the manifest lists, then drop the manifest itself. */
export async function cleanAll(root: string, manifest: Manifest): Promise<RemovedFile[]> {
  const removed: RemovedFile[] = [];
  for (const [rel, entry] of Object.entries(manifest.files)) {
    const outcome = await removeOwned(root, rel, entry.mode);
    if (outcome !== 'missing') removed.push({ path: rel, outcome });
  }
  await removeFile(absFrom(root, MANIFEST_REL));
  return removed.sort((a, b) => a.path.localeCompare(b.path));
}
